def create_data_root(root: str | Path) -> list[str]:
    """Create the layout under ``root`` (missing parts only). Returns the folders that were created.

    Never moves, renames or deletes anything. README files are (re)written only when missing or when
    they were generated by the tool; a README the user edited is left alone.
    """
    root_path = Path(root)
    created: list[str] = []
    if not root_path.exists():
        root_path.mkdir(parents=True)
        created.append(".")
    for spec in FOLDERS:
        target = folder_path(root_path, spec.key)
        if not target.exists():
            target.mkdir(parents=True)
            created.append(spec.path.replace("/", os.sep))
        _write_generated(target / "README.txt", _folder_readme(spec))
    elevation = root_path / "01_Elevation"
    _write_generated(
        elevation / "README.txt",
        README_HEADER + f" {__version__}\n\nPut the DTM in DTM\\, the DSM in DSM\\ and lidar in Source_PointCloud\\.\n"
        "Files directly in this folder are not used.\n",
    )
    _write_generated(root_path / "README.txt", _root_readme())
    marker_path = root_path / MARKER_NAME
    marker: dict[str, Any] = {}
    if marker_path.is_file():
        try:
            marker = json.loads(marker_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            marker = {}
    now = _dt.datetime.now().isoformat(timespec="seconds")
    marker.update(
        {
            "_license": f"SPDX-License-Identifier: {LICENSE_ID}",
            "_copyright": COPYRIGHT,
            "kind": "HLZ data folder",
            "layout_version": LAYOUT_VERSION,
            "folders": {spec.key: spec.path for spec in FOLDERS},
        }
    )
    marker.setdefault("created", now)
    marker.setdefault("created_by", f"HLZ Suitability Tool {__version__}")
    marker["updated"] = now
    marker["updated_by"] = f"HLZ Suitability Tool {__version__}"
    marker_path.write_text(json.dumps(marker, indent=2) + "\n", encoding="utf-8")
    return created


def _write_generated(path: Path, text: str) -> None:
    if path.exists():
        try:
            with path.open(encoding="utf-8", errors="replace") as stream:
                first = stream.readline()
        except OSError:
            return
        if not first.startswith(README_HEADER):
            return  # edited by the user: keep it
    try:
        path.write_text(text, encoding="utf-8")
    except OSError:
        pass


