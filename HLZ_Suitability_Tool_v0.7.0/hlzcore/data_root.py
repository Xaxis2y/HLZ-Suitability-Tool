_TIFF_TYPES = {1: ("B", 1), 2: ("s", 1), 3: ("H", 2), 4: ("I", 4), 5: ("I", 8), 6: ("b", 1), 7: ("B", 1),
               8: ("h", 2), 9: ("i", 4), 10: ("i", 8), 11: ("f", 4), 12: ("d", 8), 16: ("Q", 8), 17: ("q", 8), 18: ("Q", 8)}
_SKIP_TAGS = {273, 279, 324, 325, 320, 700, 34377, 37724, 50839}  # offsets, byte counts, colour maps, XMP, Photoshop
_COMPRESSION = {1: "none", 2: "CCITT", 5: "LZW", 7: "JPEG", 8: "Deflate", 32946: "Deflate", 32773: "PackBits",
                34887: "LERC", 34925: "LZMA", 50000: "ZSTD", 50001: "WebP"}


def read_tiff_ifds(path: str | Path, max_ifds: int = 64) -> list[dict[int, Any]]:
    """Tags of every IFD (the first fully; later ones only their size tags). Classic and BigTIFF."""
    ifds: list[dict[int, Any]] = []
    with open(path, "rb") as stream:
        head = stream.read(16)
        if head[:2] == b"II":
            order = "<"
        elif head[:2] == b"MM":
            order = ">"
        else:
            raise ValueError("not a TIFF file")
        magic = struct.unpack(order + "H", head[2:4])[0]
        if magic == 42:
            big = False
            offset = struct.unpack(order + "I", head[4:8])[0]
        elif magic == 43:
            big = True
            offset = struct.unpack(order + "Q", head[8:16])[0]
        else:
            raise ValueError("not a TIFF file")
        entry_size, count_fmt, offset_fmt = (20, "Q", "Q") if big else (12, "H", "I")
        seen: set[int] = set()
        while offset and offset not in seen and len(ifds) < max_ifds:
            seen.add(offset)
            stream.seek(offset)
            raw_count = stream.read(8 if big else 2)
            if len(raw_count) < (8 if big else 2):
                break
            count = struct.unpack(order + count_fmt, raw_count)[0]
            if count > 4096:
                break
            raw = stream.read(count * entry_size)
            raw_next = stream.read(8 if big else 4)
            next_offset = struct.unpack(order + offset_fmt, raw_next)[0] if len(raw_next) == (8 if big else 4) else 0
            tags: dict[int, Any] = {}
            first = not ifds
            for index in range(count):
                entry = raw[index * entry_size:(index + 1) * entry_size]
                if len(entry) < entry_size:
                    break
                if big:
                    tag, kind, n = struct.unpack(order + "HHQ", entry[:12])
                    field_bytes = entry[12:20]
                else:
                    tag, kind, n = struct.unpack(order + "HHI", entry[:8])
                    field_bytes = entry[8:12]
                if tag in _SKIP_TAGS or (not first and tag not in (254, 256, 257)):
                    continue
                spec = _TIFF_TYPES.get(kind)
                if spec is None:
                    continue
                char, size = spec
                total = n * size
                if total > 2_000_000:
                    continue
                if total <= len(field_bytes):
                    data = field_bytes[:total]
                else:
                    pointer = struct.unpack(order + offset_fmt, field_bytes)[0]
                    stream.seek(pointer)
                    data = stream.read(total)
                    if len(data) < total:
                        continue
                if kind == 2:
                    tags[tag] = data.decode("latin-1")
                elif kind in (5, 10):
                    values = struct.unpack(order + char * (2 * n), data)
                    tags[tag] = tuple(a / b if b else 0.0 for a, b in zip(values[::2], values[1::2]))
                else:
                    tags[tag] = struct.unpack(order + char * n, data)
            ifds.append(tags)
            offset = next_offset
    return ifds


def parse_geokeys(tags: dict[int, Any]) -> dict[int, Any]:
    directory = tags.get(34735)
    if not directory or len(directory) < 4:
        return {}
    doubles = tags.get(34736, ())
    ascii_params = tags.get(34737, "")
    keys: dict[int, Any] = {}
    for index in range(int(directory[3])):
        base = 4 + index * 4
        if base + 3 >= len(directory):
            break
        key_id, location, count, value = directory[base:base + 4]
        if location == 0:
            keys[key_id] = value
        elif location == 34736:
            keys[key_id] = tuple(doubles[value:value + count])
        elif location == 34737:
            keys[key_id] = ascii_params[value:value + count].strip("|\x00 ")
    return keys


def _crs_from_geokeys(keys: dict[int, Any]) -> CrsInfo:
    model = keys.get(1024)
    linear = _UNIT_CODES.get(int(keys.get(3076, 0) or 0), "")
    citation = str(keys.get(3073) or keys.get(1026) or "")
    pcs = int(keys.get(3072, 0) or 0)
    gcs = int(keys.get(2048, 0) or 0)
    info = CrsInfo(source="GeoTIFF keys")
    if pcs and pcs != 32767:
        info = _crs_from_epsg(pcs, linear)
        info.source = "GeoTIFF keys"
        if citation and not info.name:
            info.name = citation
    elif model == 1 or pcs == 32767:
        info.kind, info.unit, info.name = "projected", linear, citation
    elif model == 2 or gcs:
        info = _crs_from_epsg(gcs, "degree") if gcs and gcs != 32767 else CrsInfo(kind="geographic", unit="degree")
        info.source = "GeoTIFF keys"
        info.name = info.name or citation or "geographic"
    if linear and info.kind == "projected":
        info.unit = linear
    vertical_code = int(keys.get(4096, 0) or 0)
    if vertical_code and vertical_code != 32767:
        info.vertical = _VERTICAL_NAMES.get(vertical_code, f"EPSG:{vertical_code}")
    elif keys.get(4097):
        info.vertical = str(keys.get(4097))
    info.vertical_unit = _UNIT_CODES.get(int(keys.get(4099, 0) or 0), "")
    _utm_from_name(info)
    return info


def _merge_crs(primary: CrsInfo, fallback: CrsInfo) -> CrsInfo:
    """Fill what the GeoTIFF keys left open from a WKT (.aux.xml or .prj)."""
    if primary.kind == "unknown":
        fallback.vertical = fallback.vertical or primary.vertical
        fallback.vertical_unit = fallback.vertical_unit or primary.vertical_unit
        return fallback
    if not primary.unit and fallback.unit:
        primary.unit = fallback.unit
    if (not primary.name or primary.name.lower() in ("unknown", "projected")) and fallback.name:
        primary.name = fallback.name
    if not primary.epsg and fallback.epsg:
        primary.epsg = fallback.epsg
    if not primary.vertical and fallback.vertical:
        primary.vertical = fallback.vertical
    if primary.utm_zone is None and fallback.utm_zone is not None:
        primary.utm_zone, primary.utm_north = fallback.utm_zone, fallback.utm_north
    primary.web_mercator = primary.web_mercator or fallback.web_mercator
    return primary


def read_aux_xml(raster_path: Path) -> dict[str, Any]:
    """Statistics, NoData and SRS from a GDAL/ArcGIS ``.aux.xml`` sidecar (empty dict when absent)."""
    sidecar = raster_path.with_name(raster_path.name + ".aux.xml")
    if not sidecar.is_file():
        return {}
    try:
        tree = ET.parse(sidecar)
    except (ET.ParseError, OSError):
        return {}
    out: dict[str, Any] = {}
    root = tree.getroot()
    srs = root.find("SRS")
    if srs is not None and srs.text:
        out["wkt"] = srs.text
    band = root.find("PAMRasterBand")
    if band is not None:
        nodata = band.find("NoDataValue")
        if nodata is not None and nodata.text:
            out["nodata"] = nodata.text.strip()
        stats: dict[str, float] = {}
        for item in band.iter("MDI"):
            key = (item.get("key") or "").upper()
            if key.startswith("STATISTICS_") and item.text:
                try:
                    stats[key[len("STATISTICS_"):].lower()] = float(item.text)
                except ValueError:
                    pass
        if {"minimum", "maximum"} <= set(stats):
            out["stats"] = {"min": stats["minimum"], "max": stats["maximum"], "mean": stats.get("mean", float("nan"))}
    return out


def _sidecar_wkt(path: Path) -> str:
    for candidate in (path.with_suffix(".prj"), path.with_name(path.name + ".prj")):
        if candidate.is_file():
            try:
                return candidate.read_text(encoding="utf-8", errors="replace")
            except OSError:
                return ""
    return ""


def _world_file(path: Path) -> tuple[float, float, float, float, float, float] | None:
    suffix = path.suffix.lower()
    names = [path.with_suffix(".tfw"), path.with_suffix(".tifw"), path.with_suffix(".wld"),
             path.with_name(path.name + "w"), path.with_suffix(suffix[:2] + suffix[-1:] + "w")]
    for candidate in names:
        if candidate.is_file():
            try:
                values = [float(line) for line in candidate.read_text().split() if line.strip()]
            except (OSError, ValueError):
                return None
            if len(values) >= 6:
                return tuple(values[:6])  # type: ignore[return-value]
    return None


def inspect_geotiff(path: Path, dataset: Dataset) -> None:
    ifds = read_tiff_ifds(path)
    if not ifds:
        raise ValueError("no image directory in the TIFF")
    tags = ifds[0]
    width = int(tags.get(256, (0,))[0])
    height = int(tags.get(257, (0,))[0])
    bands = int(tags.get(277, (1,))[0])
    bits = int(tags.get(258, (8,))[0])
    sample_format = int(tags.get(339, (1,))[0])
    dataset.width, dataset.height, dataset.bands = width, height, bands
    dataset.dtype = {1: "uint", 2: "int", 3: "float"}.get(sample_format, "uint") + str(bits)
    dataset.compression = _COMPRESSION.get(int(tags.get(259, (1,))[0]), f"code {tags.get(259, (1,))[0]}")
    dataset.tiled = 322 in tags
    nodata = tags.get(42113)
    if isinstance(nodata, str) and nodata.strip("\x00 "):
        dataset.nodata = nodata.strip("\x00 ")
    keys = parse_geokeys(tags)
    pixel_is_point = int(keys.get(1025, 1) or 1) == 2
    if 33550 in tags and 33922 in tags:
        scale, tie = tags[33550], tags[33922]
        sx, sy = float(scale[0]), float(scale[1])
        i, j, x, y = float(tie[0]), float(tie[1]), float(tie[3]), float(tie[4])
        x0, y0 = x - i * sx, y + j * sy
        if pixel_is_point:
            x0, y0 = x0 - sx / 2.0, y0 + sy / 2.0
        dataset.cell_w, dataset.cell_h = sx, sy
        dataset.extent = (x0, y0 - height * sy, x0 + width * sx, y0)
    elif 34264 in tags:
        m = tags[34264]
        a, b, c, d, e, f = float(m[0]), float(m[1]), float(m[3]), float(m[4]), float(m[5]), float(m[7])
        dataset.rotated = abs(b) > 1e-9 or abs(d) > 1e-9
        dataset.cell_w, dataset.cell_h = abs(a), abs(e)
        dataset.extent = (c, f - height * abs(e), c + width * abs(a), f)
    else:
        world = _world_file(path)
        if world:
            a, d, b, e, c, f = world
            dataset.rotated = abs(b) > 1e-9 or abs(d) > 1e-9
            dataset.cell_w, dataset.cell_h = abs(a), abs(e)
            x0, y0 = c - a / 2.0, f - e / 2.0
            dataset.extent = (x0, y0 - height * abs(e), x0 + width * abs(a), y0)
    crs = _crs_from_geokeys(keys) if keys else CrsInfo()
    aux = read_aux_xml(path)
    wkt = aux.get("wkt") or _sidecar_wkt(path)
    if wkt:
        crs = _merge_crs(crs, crs_from_wkt(wkt, ".aux.xml/.prj"))
    dataset.crs = crs
    if aux.get("nodata") and not dataset.nodata:
        dataset.nodata = aux["nodata"]
    if aux.get("stats"):
        dataset.stats = aux["stats"]


def _gdal_transform_to(dataset: Dataset, transform: list[float]) -> None:
    x0, a, b, y0, d, e = transform
    dataset.rotated = abs(b) > 1e-9 or abs(d) > 1e-9
    dataset.cell_w, dataset.cell_h = abs(a), abs(e)
    if dataset.width and dataset.height:
        dataset.extent = (x0, y0 - dataset.height * abs(e), x0 + dataset.width * abs(a), y0)


def inspect_vrt(path: Path, dataset: Dataset) -> None:
    root = ET.parse(path).getroot()
    dataset.width = int(root.get("rasterXSize", "0"))
    dataset.height = int(root.get("rasterYSize", "0"))
    bands = root.findall("VRTRasterBand")
    dataset.bands = len(bands)
    if bands:
        dataset.dtype = (bands[0].get("dataType") or "").lower()
        nodata = bands[0].find("NoDataValue")
        if nodata is not None and nodata.text:
            dataset.nodata = nodata.text.strip()
    transform = root.find("GeoTransform")
    if transform is not None and transform.text:
        _gdal_transform_to(dataset, [float(v) for v in transform.text.split(",")])
    srs = root.find("SRS")
    if srs is not None and srs.text:
        dataset.crs = crs_from_wkt(srs.text, "VRT")
    aux = read_aux_xml(path)
    if aux.get("stats"):
        dataset.stats = aux["stats"]


def inspect_ascii_grid(path: Path, dataset: Dataset) -> None:
    header: dict[str, str] = {}
    with open(path, encoding="ascii", errors="replace") as stream:
        for _ in range(7):
            parts = stream.readline().split()
            if len(parts) == 2 and parts[0][0].isalpha():
                header[parts[0].lower()] = parts[1]
    dataset.width, dataset.height = int(header["ncols"]), int(header["nrows"])
    cell = float(header["cellsize"])
    dataset.bands, dataset.cell_w, dataset.cell_h, dataset.dtype = 1, cell, cell, "text"
    x0 = float(header.get("xllcorner", header.get("xllcenter", "0")))
    y0 = float(header.get("yllcorner", header.get("yllcenter", "0")))
    if "xllcenter" in header:
        x0, y0 = x0 - cell / 2.0, y0 - cell / 2.0
    dataset.extent = (x0, y0, x0 + dataset.width * cell, y0 + dataset.height * cell)
    dataset.nodata = header.get("nodata_value")
    wkt = _sidecar_wkt(path)
    if wkt:
        dataset.crs = crs_from_wkt(wkt, ".prj")


