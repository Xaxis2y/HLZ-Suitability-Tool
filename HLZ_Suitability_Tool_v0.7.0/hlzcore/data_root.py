def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="python -m hlzcore.data_root",
                                     description="Create and audit an HLZ data folder (standard library only).")
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)
    init = sub.add_parser("init", help="Create the folder layout (missing parts only), then audit it")
    init.add_argument("root", help=f"Data folder to create, e.g. C:\\GIS\\{DEFAULT_ROOT_NAME}")
    init.add_argument("--no-audit", action="store_true", help="Only create the folders")
    audit = sub.add_parser("audit", help="Check what is in a data folder and write a report to 09_Audit")
    audit.add_argument("root", help="The data folder")
    audit.add_argument("--create", action="store_true", help="Also create missing standard folders")
    for command in (init, audit):
        command.add_argument("--aircraft-profile", help="Aircraft profile for the AOI margin check (default: generic medium)")
        command.add_argument("--no-report", action="store_true", help="Do not write report files")
        command.add_argument("--quiet", action="store_true", help="Print only the result line")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        root = Path(args.root).expanduser()
        if args.command == "init":
            created = create_data_root(root)
            print(f"HLZ data folder: {root.resolve()}")
            print("Created: " + (", ".join(created) if created else "nothing (everything already existed)"))
            if args.no_audit:
                return 0
        result = audit_data_root(root, create=getattr(args, "create", False), aircraft_profile=args.aircraft_profile,
                                 write_reports=not args.no_report)
        if args.quiet:
            print(f"{result.status}: {result.root}")
        else:
            print(format_audit_text(result))
        return 2 if result.status == STATUS_NOT_READY else 0
    except Exception as error:  # noqa: BLE001 - command-line boundary
        print(f"HLZ data folder: {type(error).__name__}: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
