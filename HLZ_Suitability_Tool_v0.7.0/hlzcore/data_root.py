def _rel(path: Path, root: Path) -> str:
    try:
        return str(path.relative_to(root))
    except ValueError:
        return str(path)


def _is_sidecar(name: str) -> bool:
    lowered = name.lower()
    return lowered in IGNORED_NAMES or any(lowered.endswith(suffix) for suffix in SIDECAR_SUFFIXES)


def inspect_obstacle_list(path: Path, dataset: Dataset) -> None:
    """FAA DOF (.dat) or CSV obstacle list: count, extent and how many heights are missing (needs NumPy, else unchecked)."""
    suffix = path.suffix.lower()
    dataset.fmt = "FAA DOF (.dat)" if suffix == ".dat" else "CSV obstacle list"
    dataset.geometry = "Point"
    dataset.crs = _crs_from_epsg(4326, "degree")
    try:
        from .obstacles import ObstacleError, read_obstacle_file
    except ImportError:
        dataset.readable = False
        dataset.note = "Not checked here: NumPy is needed to read obstacle lists (it is part of the HLZ environment)."
        return
    try:
        result = read_obstacle_file(path)
    except ObstacleError as error:
        dataset.readable = False
        dataset.note = str(error)
        return
    points = [part[0] for obstacle in result.obstacles for part in obstacle.parts[:1]]
    dataset.feature_count = len(result.obstacles)
    if points:
        xs = [p[0] for p in points]
        ys = [p[1] for p in points]
        pad = 1.0e-5  # a single obstacle has no extent: give it about a metre so the overlap test works
        dataset.extent = (min(xs) - pad, min(ys) - pad, max(xs) + pad, max(ys) + pad)
    parts = [f"{len(result.obstacles):,} obstacle(s)"]
    if result.skipped:
        parts.append(f"{result.skipped:,} record(s) skipped (no position, or dismantled)")
    if result.assumed:
        parts.append(f"{result.assumed:,} without a height (the default is used)")
    if result.height_field:
        parts.append(f"height from '{result.height_field}'")
    dataset.note = "; ".join(parts)
    dataset.stats = {"assumed_heights": float(result.assumed)}


def inspect_path(path: Path, folder_key: str | None, root: Path, inspector: Inspector | None = None) -> list[Dataset]:
    """Datasets found at ``path`` (a file or a container folder such as .gdb)."""
    suffix = path.suffix.lower()
    name = path.name
    base = Dataset(path=str(path), rel=_rel(path, root), name=name, folder_key=folder_key, kind="other", fmt=suffix or "file")
    if path.is_dir():
        base.kind = "geodatabase" if suffix in (".gdb", ".sde") else "raster"
        base.fmt = CONTAINER_DIRS.get(suffix, "folder")
        base.size_bytes = _folder_size(path)
        if inspector is not None:
            try:
                found = inspector(path)
            except Exception as error:  # noqa: BLE001 - never let one dataset stop the audit
                found = None
                base.note = f"Could not be read: {error}"
            if found is not None:
                for item in found:
                    item.folder_key = folder_key
                    item.rel = _rel(Path(item.path), root) if not item.rel else item.rel
                return found or [replace_note(base, "Empty: no feature classes or rasters inside.")]
        base.readable = False
        base.note = base.note or (
            "Contents are checked only inside ArcGIS Pro (tool '0. Set Up and Audit Data Folder')."
        )
        return [base]
    try:
        base.size_bytes = path.stat().st_size
    except OSError:
        pass
    try:
        if suffix in (".tif", ".tiff"):
            base.kind, base.fmt = "raster", "GeoTIFF"
            inspect_geotiff(path, base)
        elif suffix == ".vrt":
            base.kind, base.fmt = "raster", "GDAL virtual raster (.vrt)"
            inspect_vrt(path, base)
        elif suffix == ".asc":
            base.kind, base.fmt = "raster", "ESRI ASCII grid"
            inspect_ascii_grid(path, base)
        elif suffix in RASTER_EXTENSIONS:
            base.kind, base.fmt = "raster", suffix.lstrip(".").upper() + " raster"
            return _via_inspector(path, base, inspector)
        elif suffix in (".dat", ".csv", ".txt") and folder_key == "obstacles":
            base.kind = "vector"
            inspect_obstacle_list(path, base)
        elif suffix == ".shp":
            base.kind, base.fmt = "vector", "Shapefile"
            inspect_shapefile(path, base)
        elif suffix == ".geojson" or (suffix == ".json" and folder_key not in ("profiles",)):
            base.kind, base.fmt = "vector", "GeoJSON"
            inspect_geojson(path, base)
        elif suffix == ".gpkg":
            return inspect_geopackage(path, folder_key, root)
        elif suffix in (".kml", ".kmz"):
            base.kind, base.fmt, base.readable = "vector", "KML", False
            base.note = ("KML/KMZ is not used directly. Convert it with 'KML To Layer' and save the result as a "
                         "shapefile or feature class here.")
        elif suffix in (".gml", ".fgb"):
            base.kind, base.fmt = "vector", suffix.lstrip(".").upper()
            return _via_inspector(path, base, inspector)
        elif suffix in POINTCLOUD_EXTENSIONS:
            base.kind, base.fmt = "pointcloud", suffix.lstrip(".").upper() + " point cloud"
        elif suffix in ARCHIVE_EXTENSIONS:
            base.kind, base.fmt = "archive", suffix.lstrip(".").upper() + " archive"
        elif suffix in (".json", ".yaml", ".yml") and folder_key == "profiles":
            base.kind, base.fmt = "profile", "Profile"
        elif suffix in DOCUMENT_EXTENSIONS:
            base.kind, base.fmt = "document", suffix.lstrip(".").upper()
    except Exception as error:  # noqa: BLE001 - report, never crash
        base.readable = False
        base.note = f"Could not be read: {error}"
        if inspector is not None and base.kind in ("raster", "vector"):
            return _via_inspector(path, base, inspector)
    return [base]


def replace_note(dataset: Dataset, note: str) -> Dataset:
    dataset.note = note
    return dataset


def _via_inspector(path: Path, base: Dataset, inspector: Inspector | None) -> list[Dataset]:
    if inspector is not None:
        try:
            found = inspector(path)
        except Exception as error:  # noqa: BLE001
            found = None
            base.note = f"ArcGIS could not read it: {error}"
        if found:
            for item in found:
                item.folder_key = base.folder_key
                item.rel = item.rel or base.rel
            return found
    base.readable = False
    base.note = base.note or ("Header not checked outside ArcGIS Pro. GeoTIFF (.tif) is checked everywhere; run "
                              "'0. Set Up and Audit Data Folder' in ArcGIS Pro for this format.")
    return [base]


def _folder_size(path: Path, limit: int = 20000) -> int:
    total = 0
    seen = 0
    for current, _dirs, files in os.walk(path):
        for name in files:
            seen += 1
            if seen > limit:
                return total
            try:
                total += (Path(current) / name).stat().st_size
            except OSError:
                pass
    return total


def _iter_entries(folder: Path, max_depth: int = 3) -> Iterable[Path]:
    """Files and container folders (.gdb, .crf) below ``folder``; plain sub-folders are walked."""
    try:
        entries = sorted(folder.iterdir(), key=lambda item: item.name.lower())
    except OSError:
        return
    for entry in entries:
        if entry.name.startswith(".") or entry.name.startswith("~$"):
            continue
        if entry.is_dir():
            if entry.suffix.lower() in CONTAINER_DIRS:
                yield entry
            elif max_depth > 0 and not _is_layout_folder(entry):
                yield from _iter_entries(entry, max_depth - 1)
        elif not _is_sidecar(entry.name):
            yield entry


_LAYOUT_PATHS: set[str] = set()


def _is_layout_folder(path: Path) -> bool:
    """True for a standard sub-folder (so the walk of a parent does not descend into it)."""
    return path.as_posix().rstrip("/").lower() in _LAYOUT_PATHS


def scan_data_root(root: str | Path, inspector: Inspector | None = None) -> list[Dataset]:
    """Every dataset in the standard folders, plus loose files elsewhere under the root."""
    root_path = Path(root)
    _LAYOUT_PATHS.clear()
    _LAYOUT_PATHS.update(folder_path(root_path, spec.key).as_posix().lower() for spec in FOLDERS)
    datasets: list[Dataset] = []
    for key in SCAN_KEYS:
        folder = folder_path(root_path, key)
        if not folder.is_dir():
            continue
        for entry in _iter_entries(folder):
            datasets.extend(inspect_path(entry, key, root_path, inspector))
    # Loose files: directly in the root, in 01_Elevation, and in unknown top-level folders.
    standard_top = {spec.path.split("/")[0].lower() for spec in FOLDERS}
    loose_places = [root_path, root_path / "01_Elevation"]
    if root_path.is_dir():
        for child in sorted(root_path.iterdir(), key=lambda item: item.name.lower()):
            if child.is_dir() and child.name.lower() not in standard_top and child.suffix.lower() not in CONTAINER_DIRS \
                    and not child.name.startswith("."):
                loose_places.append(child)
    for place in loose_places:
        if not place.is_dir():
            continue
        depth = 0 if place in (root_path, root_path / "01_Elevation") else 2
        for entry in _iter_entries(place, depth):
            datasets.extend(inspect_path(entry, None, root_path, inspector))
    return datasets


