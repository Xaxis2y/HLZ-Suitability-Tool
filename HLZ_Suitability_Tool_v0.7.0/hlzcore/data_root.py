def format_audit_text(result: AuditResult) -> str:
    counts = result.counts()
    inputs = result.inputs
    lines = [
        f"HLZ Suitability Tool {result.tool_version} - data folder audit",
        f"SPDX-License-Identifier: {LICENSE_ID} | {COPYRIGHT}",
        "=" * 100,
        f"Data folder : {result.root}",
        f"Checked     : {result.checked_at}",
        f"Aircraft    : {result.aircraft} (DTM margin needed around an AOI: {result.buffer_m:,.0f} m)",
        f"RESULT      : {STATUS_TEXT[result.status]}",
        f"Findings    : {counts[LEVEL_FAIL]} FAIL, {counts[LEVEL_WARN]} WARN, {counts[LEVEL_INFO]} INFO, {counts[LEVEL_PASS]} PASS",
        "",
        "INPUTS THE ANALYSIS WILL USE (filled in when you choose this data folder)",
        f"  DTM             : {inputs.dtm or '-- none --'}",
        f"  DSM             : {inputs.dsm or '-- none --'}",
        f"  Exclusion areas : {len(inputs.exclusions)} layer(s)",
    ]
    lines += [f"                    {path}" for path in inputs.exclusions]
    lines += [
        f"  Obstacles       : {len(inputs.obstacles)} source(s)" + ("" if inputs.obstacles else " (none: towers and wires are not considered)"),
    ]
    lines += [f"                    {path}" for path in inputs.obstacles]
    lines += [
        f"  AOI             : {inputs.aoi or '-- none (map view or whole DTM) --'}",
        f"  Output folder   : {inputs.runs_folder or '-- not set --'}",
    ]
    if inputs.centres:
        lines.append(f"  Search centres  : {len(inputs.centres)} layer(s) available (choose in the dialog)")
    lines += [f"  Note            : {note}" for note in inputs.notes]
    for level in (LEVEL_FAIL, LEVEL_WARN, LEVEL_INFO, LEVEL_PASS):
        items = [item for item in result.findings if item.level == level]
        if not items:
            continue
        lines += ["", f"{level} ({len(items)})", "-" * 100]
        for item in items:
            lines.append(f"[{level}] {_area_title(item.area)}: {item.message}")
            if item.action:
                lines.append(f"        -> {item.action}")
    lines += ["", "INVENTORY", "-" * 100]
    for dataset in result.datasets:
        detail = dataset.fmt
        if dataset.kind == "raster" and dataset.width:
            detail += f", {dataset.width}x{dataset.height}, cell {_fmt_cell(dataset)}, {dataset.dtype}"
        elif dataset.kind == "vector" and dataset.geometry:
            detail += f", {dataset.geometry}, {_features(dataset.feature_count)}"
        lines.append(f"  {dataset.rel:<60} {detail} | {_human_size(dataset.size_bytes)} | CRS {dataset.crs.label()}")
    if not result.datasets:
        lines.append("  (no data files yet)")
    if result.reports:
        lines += ["", "REPORTS"] + [f"  {kind:<5}: {path}" for kind, path in result.reports.items()]
    lines.append("")
    return "\n".join(lines)


def _features(count: int | None) -> str:
    if count is None:
        return "? features"
    return "1 feature" if count == 1 else f"{count:,} features"


def _human_size(size: int) -> str:
    value = float(size)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if value < 1024.0 or unit == "TB":
            return f"{value:,.0f} {unit}" if unit == "B" else f"{value:,.1f} {unit}"
        value /= 1024.0
    return f"{size} B"


def _svg_extents(result: AuditResult) -> str:
    """A small diagram of the DTM, DSM, AOI (+ margin), exclusion and centre extents (bounding boxes)."""
    datasets = {d.path: d for d in result.datasets}
    dtm = datasets.get(result.inputs.dtm or "")
    if dtm is None or not dtm.extent:
        return ""
    shapes: list[tuple[str, tuple[float, float, float, float], str]] = [("DTM", dtm.extent, "dtm")]
    dsm = datasets.get(result.inputs.dsm or "")
    if dsm is not None:
        box = extent_in(dsm, dtm.crs)
        if box:
            shapes.append(("DSM", box, "dsm"))
    for path in result.inputs.exclusions:
        item = datasets.get(path)
        box = extent_in(item, dtm.crs) if item else None
        if box:
            shapes.append((item.name, box, "water"))  # type: ignore[union-attr]
    aoi = datasets.get(result.inputs.aoi or "")
    if aoi is not None:
        box = extent_in(aoi, dtm.crs)
        if box:
            b = result.buffer_m
            shapes.append(("AOI + approach margin", (box[0] - b, box[1] - b, box[2] + b, box[3] + b), "margin"))
            shapes.append(("AOI", box, "aoi"))
    xs = [v for _, box, _ in shapes for v in (box[0], box[2])]
    ys = [v for _, box, _ in shapes for v in (box[1], box[3])]
    x_min, x_max, y_min, y_max = min(xs), max(xs), min(ys), max(ys)
    span = max(x_max - x_min, y_max - y_min, 1.0)
    pad = span * 0.04
    x_min, y_min, x_max, y_max = x_min - pad, y_min - pad, x_max + pad, y_max + pad
    width, height = 640.0, 640.0 * (y_max - y_min) / max(x_max - x_min, 1e-9)
    height = min(max(height, 200.0), 640.0)
    sx, sy = width / (x_max - x_min), height / (y_max - y_min)
    parts = []
    for label, box, css in shapes:
        x = (box[0] - x_min) * sx
        y = (y_max - box[3]) * sy
        w = max((box[2] - box[0]) * sx, 1.0)
        h = max((box[3] - box[1]) * sy, 1.0)
        parts.append(f'<rect class="{css}" x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}">'
                     f"<title>{html.escape(label)}</title></rect>")
    legend = "".join(
        f'<span class="key {css}"></span>{html.escape(text)} '
        for text, css in (("DTM", "dtm"), ("DSM", "dsm"), ("Water / exclusion (bounding box)", "water"),
                          ("AOI", "aoi"), (f"AOI + {result.buffer_m:,.0f} m approach margin", "margin"))
        if any(s[2] == css for s in shapes)
    )
    return (f'<svg viewBox="0 0 {width:.0f} {height:.0f}" role="img" aria-label="Extents of the inputs">{"".join(parts)}</svg>'
            f'<p class="legend">{legend}</p><p class="muted">Bounding boxes in the DTM coordinate system. The approach '
            "margin must lie inside the DTM.</p>")


