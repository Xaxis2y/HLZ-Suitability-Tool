def write_audit_reports(result: AuditResult) -> dict[str, str]:
    folder = folder_path(result.root, "audit")
    folder.mkdir(parents=True, exist_ok=True)
    stamp = _dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    base = folder / f"HLZ_Data_Audit_{stamp}"
    paths = {"html": str(base) + ".html", "text": str(base) + ".txt", "json": str(base) + ".json",
             "latest": str(folder / "HLZ_Data_Audit_latest.html")}
    result.reports = dict(paths)
    page = format_audit_html(result)
    Path(paths["html"]).write_text(page, encoding="utf-8")
    Path(paths["latest"]).write_text(page, encoding="utf-8")
    Path(paths["text"]).write_text(format_audit_text(result), encoding="utf-8")
    Path(paths["json"]).write_text(json.dumps(result.to_dict(), indent=2, default=str), encoding="utf-8")
    return paths


