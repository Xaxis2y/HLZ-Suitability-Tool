@dataclass
class CrsInfo:
    kind: str = "unknown"  # projected | geographic | unknown
    name: str = ""
    epsg: int | None = None
    unit: str = ""  # metre | foot | us-foot | degree | other text
    utm_zone: int | None = None
    utm_north: bool = True
    web_mercator: bool = False
    vertical: str = ""
    vertical_unit: str = ""
    source: str = ""

    def label(self) -> str:
        if self.kind == "unknown" and not self.name:
            return "unknown"
        text = self.name or self.kind
        if self.epsg:
            text += f" (EPSG:{self.epsg})"
        if self.vertical:
            text += f" + {self.vertical}"
        return text

    @property
    def metric_projected(self) -> bool:
        return self.kind == "projected" and self.unit == "metre" and not self.web_mercator


