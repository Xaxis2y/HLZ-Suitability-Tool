_SHAPE_TYPES = {0: "Empty", 1: "Point", 3: "Line", 5: "Polygon", 8: "Point", 11: "Point", 13: "Line", 15: "Polygon",
                18: "Point", 21: "Point", 23: "Line", 25: "Polygon", 28: "Point", 31: "MultiPatch"}
_GEOMETRY_WORDS = {
    "point": "Point", "multipoint": "Point", "linestring": "Line", "multilinestring": "Line", "line": "Line",
    "polyline": "Line", "polygon": "Polygon", "multipolygon": "Polygon", "curvepolygon": "Polygon",
    "multisurface": "Polygon", "multicurve": "Line", "compoundcurve": "Line", "circularstring": "Line",
}


def inspect_shapefile(path: Path, dataset: Dataset) -> None:
    with open(path, "rb") as stream:
        header = stream.read(100)
    if len(header) < 100 or struct.unpack(">i", header[:4])[0] != 9994:
        raise ValueError("not a valid shapefile (.shp header)")
    shape_type = struct.unpack("<i", header[32:36])[0]
    dataset.geometry = _SHAPE_TYPES.get(shape_type, "Unknown")
    x_min, y_min, x_max, y_max = struct.unpack("<4d", header[36:68])
    file_words = struct.unpack(">i", header[24:28])[0]
    dataset.extent = None if file_words <= 50 else (x_min, y_min, x_max, y_max)
    dbf = path.with_suffix(".dbf")
    if dbf.is_file():
        with open(dbf, "rb") as stream:
            head = stream.read(8)
        if len(head) == 8:
            dataset.feature_count = struct.unpack("<I", head[4:8])[0]
    elif file_words <= 50:
        dataset.feature_count = 0
    missing = [ext for ext in (".shx", ".dbf") if not path.with_suffix(ext).is_file()]
    if missing:
        dataset.readable = False
        dataset.note = f"Incomplete shapefile: {', '.join(missing)} missing. Copy all parts of the shapefile."
    wkt = _sidecar_wkt(path)
    if wkt:
        dataset.crs = crs_from_wkt(wkt, ".prj")


def _coordinate_bbox(coordinates: Any, box: list[float]) -> None:
    stack = [coordinates]
    while stack:
        item = stack.pop()
        if not isinstance(item, list) or not item:
            continue
        if isinstance(item[0], (int, float)):
            if len(item) >= 2:
                x, y = float(item[0]), float(item[1])
                box[0], box[1] = min(box[0], x), min(box[1], y)
                box[2], box[3] = max(box[2], x), max(box[3], y)
        else:
            stack.extend(item)


def _geojson_geometries(data: Any) -> Iterable[dict[str, Any]]:
    kind = data.get("type") if isinstance(data, dict) else None
    if kind == "FeatureCollection":
        for feature in data.get("features") or []:
            geometry = feature.get("geometry") if isinstance(feature, dict) else None
            if isinstance(geometry, dict):
                yield geometry
    elif kind == "Feature":
        if isinstance(data.get("geometry"), dict):
            yield data["geometry"]
    elif kind:
        yield data


GEOJSON_FULL_READ_BYTES = 150 * 1024 * 1024


def inspect_geojson(path: Path, dataset: Dataset) -> None:
    size = path.stat().st_size
    if size > GEOJSON_FULL_READ_BYTES:
        with open(path, encoding="utf-8", errors="replace") as stream:
            head = stream.read(2_000_000)
        types = {_GEOMETRY_WORDS.get(word.lower(), "Unknown") for word in
                 re.findall(r'"type"\s*:\s*"(Point|MultiPoint|LineString|MultiLineString|Polygon|MultiPolygon)"', head)}
        dataset.geometry = types.pop() if len(types) == 1 else ("Mixed" if types else "Unknown")
        dataset.note = "Large GeoJSON: only the start was read; the extent was not measured."
        dataset.crs = CrsInfo(kind="geographic", unit="degree", name="WGS 84", epsg=4326, source="GeoJSON default")
        return
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    if not isinstance(data, dict) or data.get("type") not in (
        "FeatureCollection", "Feature", "Point", "MultiPoint", "LineString", "MultiLineString", "Polygon",
        "MultiPolygon", "GeometryCollection",
    ):
        raise ValueError("not a GeoJSON file")
    types: set[str] = set()
    box = [math.inf, math.inf, -math.inf, -math.inf]
    count = 0
    pending = list(_geojson_geometries(data))
    count = len(pending) if data.get("type") == "FeatureCollection" else 1
    while pending:
        geometry = pending.pop()
        kind = str(geometry.get("type", ""))
        if kind == "GeometryCollection":
            pending.extend(g for g in geometry.get("geometries") or [] if isinstance(g, dict))
            continue
        types.add(_GEOMETRY_WORDS.get(kind.lower(), "Unknown"))
        _coordinate_bbox(geometry.get("coordinates"), box)
    dataset.feature_count = count
    dataset.geometry = types.pop() if len(types) == 1 else ("Mixed" if types else "Unknown")
    if math.isfinite(box[0]):
        dataset.extent = (box[0], box[1], box[2], box[3])
    crs_name = ""
    crs = data.get("crs")
    if isinstance(crs, dict):
        crs_name = str((crs.get("properties") or {}).get("name", ""))
    match = re.search(r"EPSG:+(\d+)", crs_name)
    if match and match.group(1) not in ("4326",):
        dataset.crs = _crs_from_epsg(int(match.group(1)))
        dataset.crs.source = "GeoJSON crs member"
    else:
        dataset.crs = CrsInfo(kind="geographic", unit="degree", name="WGS 84", epsg=4326, source="GeoJSON default")


def inspect_geopackage(path: Path, folder_key: str | None, root: Path) -> list[Dataset]:
    datasets: list[Dataset] = []
    uri = path.resolve().as_uri() + "?mode=ro"
    connection = sqlite3.connect(uri, uri=True)
    try:
        cursor = connection.cursor()
        rows = cursor.execute(
            "SELECT c.table_name, c.data_type, c.min_x, c.min_y, c.max_x, c.max_y, c.srs_id, g.geometry_type_name "
            "FROM gpkg_contents c LEFT JOIN gpkg_geometry_columns g ON g.table_name = c.table_name"
        ).fetchall()
        srs_rows = {int(r[0]): (r[1], r[2], r[3], r[4]) for r in cursor.execute(
            "SELECT srs_id, srs_name, organization, organization_coordsys_id, definition FROM gpkg_spatial_ref_sys")}
        for table, data_type, x_min, y_min, x_max, y_max, srs_id, geometry_type in rows:
            layer_path = str(path) + os.sep + "main." + str(table)
            dataset = Dataset(
                path=layer_path, rel=_rel(path, root) + os.sep + str(table), name=str(table), folder_key=folder_key,
                kind="vector" if data_type == "features" else "raster", fmt=f"GeoPackage {data_type}",
                size_bytes=path.stat().st_size,
            )
            if data_type == "features":
                dataset.geometry = _GEOMETRY_WORDS.get(str(geometry_type or "").lower(), "Unknown")
                try:
                    dataset.feature_count = int(cursor.execute(f'SELECT COUNT(*) FROM "{table}"').fetchone()[0])
                except sqlite3.Error:
                    dataset.feature_count = None
            if None not in (x_min, y_min, x_max, y_max):
                dataset.extent = (float(x_min), float(y_min), float(x_max), float(y_max))
            srs = srs_rows.get(int(srs_id)) if srs_id is not None else None
            if srs:
                name, organisation, code, definition = srs
                crs = crs_from_wkt(definition or "", "GeoPackage")
                if crs.kind == "unknown" and str(organisation).upper() == "EPSG" and code:
                    crs = _crs_from_epsg(int(code))
                if not crs.epsg and str(organisation).upper() == "EPSG" and code and int(code) > 0:
                    crs.epsg = int(code)
                crs.name = crs.name or str(name or "")
                dataset.crs = crs
            datasets.append(dataset)
    finally:
        connection.close()
    return datasets


