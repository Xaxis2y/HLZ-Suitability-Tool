def utm_from_epsg(code: int | None) -> tuple[int, bool, str] | None:
    """(zone, northern, datum) for common UTM EPSG codes, else None."""
    if not code:
        return None
    if 32601 <= code <= 32660:
        return code - 32600, True, "WGS 84"
    if 32701 <= code <= 32760:
        return code - 32700, False, "WGS 84"
    if 26901 <= code <= 26923:
        return code - 26900, True, "NAD83"
    if code in _CSRS_UTM:
        return _CSRS_UTM[code], True, "NAD83(CSRS)"
    for realization in (2, 3, 4, 6, 7, 8):
        base = 22000 + realization * 100
        if base + 7 <= code <= base + 22:
            return code - base, True, f"NAD83(CSRS)v{realization}"
    if 6330 <= code <= 6348:
        return code - 6329, True, "NAD83(2011)"
    if 25828 <= code <= 25838:
        return code - 25800, True, "ETRS89"
    return None


def _crs_from_epsg(code: int, unit: str = "") -> CrsInfo:
    info = CrsInfo(epsg=code, source="EPSG code")
    utm = utm_from_epsg(code)
    if utm:
        zone, north, datum = utm
        info.kind, info.unit, info.utm_zone, info.utm_north = "projected", "metre", zone, north
        info.name = f"{datum} / UTM zone {zone}{'N' if north else 'S'}"
    elif code in _WEB_MERCATOR:
        info.kind, info.unit, info.web_mercator, info.name = "projected", "metre", True, "WGS 84 / Pseudo-Mercator"
    elif code in (4326, 4269, 4617, 4258, 6318, 4979, 4952, 8237, 8240, 8244, 8248, 8252, 8256):
        info.kind, info.unit = "geographic", "degree"
        info.name = {4326: "WGS 84", 4269: "NAD83", 4617: "NAD83(CSRS)", 4258: "ETRS89", 6318: "NAD83(2011)"}.get(code, "geographic")
    elif 4000 <= code <= 4999:
        info.kind, info.unit = "geographic", "degree"
    elif 2000 <= code <= 32767 or 102000 <= code <= 104999:
        info.kind, info.unit = "projected", unit
    if unit and not info.unit:
        info.unit = unit
    return info


def _normalise_unit(text: str) -> str:
    lowered = text.lower().replace("_", " ").strip()
    if lowered in ("metre", "meter", "metres", "meters", "m"):
        return "metre"
    if "us" in lowered and ("foot" in lowered or "feet" in lowered):
        return "us-foot"
    if "foot" in lowered or "feet" in lowered:
        return "foot"
    if "degree" in lowered:
        return "degree"
    if "kilomet" in lowered:
        return "kilometre"
    return lowered


def _utm_from_name(info: CrsInfo) -> None:
    match = re.search(r"UTM[ _]?zone[ _]?(\d{1,2})\s*([NS])?", info.name, re.I)
    if match and info.kind == "projected":
        info.utm_zone = int(match.group(1))
        info.utm_north = (match.group(2) or "N").upper() == "N"
    if re.search(r"pseudo[ _-]?mercator|web[ _]?mercator|popular visualisation", info.name, re.I):
        info.web_mercator = True


def crs_from_wkt(text: str, source: str = "WKT") -> CrsInfo:
    """A crude but robust WKT1/WKT2 reader: kind, name, EPSG, linear unit, UTM zone, vertical datum."""
    info = CrsInfo(source=source)
    wkt = text.strip()
    if not wkt:
        return info
    vertical = ""
    head = wkt.split("[", 1)[0].upper()
    if head in ("COMPD_CS", "COMPOUNDCRS"):
        vmatch = re.search(r'(?:VERT_CS|VERTCRS|VERTICALCRS)\["([^"]+)"', wkt, re.I)
        vertical = vmatch.group(1) if vmatch else ""
        pmatch = re.search(r'((?:PROJCS|PROJCRS|PROJECTEDCRS|GEOGCS|GEOGCRS|GEOGRAPHICCRS)\[.*)', wkt, re.I | re.S)
        wkt = pmatch.group(1) if pmatch else wkt
        head = wkt.split("[", 1)[0].upper()
    if head in ("PROJCS", "PROJCRS", "PROJECTEDCRS"):
        info.kind = "projected"
    elif head in ("GEOGCS", "GEOGCRS", "GEOGRAPHICCRS", "GEODCRS"):
        info.kind = "geographic"
    name = re.match(r'\w+\["([^"]*)"', wkt)
    info.name = name.group(1).replace("_", " ") if name else ""
    authorities = re.findall(r'(?:AUTHORITY\["EPSG",\s*"?|ID\["EPSG",\s*)(\d+)', wkt, re.I)
    if authorities:
        info.epsg = int(authorities[-1])
    if info.kind == "projected":
        units = re.findall(r'(?:LENGTHUNIT|UNIT)\["([^"]+)"', wkt, re.I)
        info.unit = _normalise_unit(units[-1]) if units else ""
    elif info.kind == "geographic":
        info.unit = "degree"
    if info.epsg and info.epsg in _WEB_MERCATOR:
        info.web_mercator = True
    utm = utm_from_epsg(info.epsg)
    if utm:
        info.utm_zone, info.utm_north = utm[0], utm[1]
    _utm_from_name(info)
    info.vertical = vertical
    return info


def crs_equal(first: CrsInfo, second: CrsInfo) -> bool:
    """Strictly the same coordinate system (as far as the headers tell)."""
    if first.epsg and second.epsg:
        return first.epsg == second.epsg
    if first.name and second.name:
        return first.name.lower() == second.name.lower()
    return False


def crs_compatible(first: CrsInfo, second: CrsInfo) -> bool:
    """Close enough to compare extents directly (same EPSG, or the same UTM zone on any NAD83/WGS84 datum)."""
    if crs_equal(first, second):
        return True
    if first.utm_zone and second.utm_zone and first.kind == second.kind == "projected":
        return first.utm_zone == second.utm_zone and first.utm_north == second.utm_north
    return False


def extent_in(dataset: Dataset, target: CrsInfo) -> tuple[float, float, float, float] | None:
    """The dataset's extent expressed in ``target`` (approximately), or None when that is not possible here."""
    box = dataset.extent
    if box is None:
        return None
    if crs_compatible(dataset.crs, target):
        return box
    if dataset.crs.kind == "geographic" and target.utm_zone:
        x_min, y_min, x_max, y_max = box
        if not (-180.0 <= x_min <= 180.0 and -90.0 <= y_min <= 90.0):
            return None
        xs: list[float] = []
        ys: list[float] = []
        for step in range(9):
            t = step / 8.0
            for lon, lat in (
                (x_min + t * (x_max - x_min), y_min), (x_min + t * (x_max - x_min), y_max),
                (x_min, y_min + t * (y_max - y_min)), (x_max, y_min + t * (y_max - y_min)),
            ):
                _, _, easting, northing = latlon_to_utm(lat, lon, target.utm_zone)
                if target.utm_north and lat < 0.0:
                    northing -= 10_000_000.0
                xs.append(easting)
                ys.append(northing)
        return min(xs), min(ys), max(xs), max(ys)
    return None


