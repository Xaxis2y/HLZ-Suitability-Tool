def is_data_root(path: str | Path) -> bool:
    return (Path(path) / MARKER_NAME).is_file()


def resolve_data_root(path: str | Path) -> Path | None:
    """The data folder at ``path``: the folder itself, or its single child that holds the marker."""
    candidate = Path(path)
    if is_data_root(candidate):
        return candidate
    if candidate.is_dir():
        found = [child for child in candidate.iterdir() if child.is_dir() and is_data_root(child)]
        if len(found) == 1:
            return found[0]
    return None


