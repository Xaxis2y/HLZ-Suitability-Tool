"""HLZ data folder: a standard place for every input, and an audit of what is in it (v0.6.6).

One folder (``HLZ_DATA`` by default) holds everything an analysis needs::

    HLZ_DATA\\
        hlz_data_root.json            marker (layout version, creation info)
        README.txt                    what goes where
        01_Elevation\\DTM              REQUIRED      one bare-earth elevation raster
        01_Elevation\\DSM              RECOMMENDED   one surface raster (trees, buildings)
        01_Elevation\\Source_PointCloud OPTIONAL     LAS/LAZ kept for reference (not read)
        02_Hydrology\\                 RECOMMENDED   water polygons (lakes, rivers, reservoirs)
        03_Exclusions\\                OPTIONAL      other no-landing polygons (wetland, built-up)
        04_AOI\\                       OPTIONAL      one area-of-interest polygon
        05_Search_Centres\\            OPTIONAL      point layers to search around
        06_Reference\\                 REFERENCE     imagery, roads (not read)
        07_Profiles\\                  OPTIONAL      custom aircraft / mission / doctrine JSON
        08_Runs\\                      OUTPUT        analysis results (one sub-folder per run)
        09_Audit\\                     OUTPUT        audit reports
        10_Obstacles\\                OPTIONAL      towers, masts, wires, buildings (FAA DOF, CSV, GeoJSON, layers)

The audit reads only file headers (GeoTIFF tags, shapefile headers, GeoJSON,
GeoPackage tables, ``.aux.xml`` statistics), so it takes seconds even for
multi-gigabyte rasters. It needs nothing but the Python standard library, so
it runs inside ArcGIS Pro, in any Conda environment, or from a plain Python.
Inside ArcGIS Pro an optional ``inspector`` (``hlzcore.io_arcpy.audit_inspector``)
adds formats the standard library cannot read (file geodatabases, .img, .crf).

Command line::

    python -m hlzcore.data_root init  C:\\GIS\\HLZ_DATA
    python -m hlzcore.data_root audit C:\\GIS\\HLZ_DATA [--aircraft-profile file.json]

Exit codes: 0 = ready (possibly with warnings), 2 = not ready, 1 = error.
"""

