def select_inputs(root: str | Path, datasets: list[Dataset]) -> DiscoveredInputs:
    inputs = DiscoveredInputs(root=str(root))
    dtms = [d for d in datasets if d.folder_key == "dtm" and d.kind == "raster"]
    dsms = [d for d in datasets if d.folder_key == "dsm" and d.kind == "raster"]
    if len(dtms) == 1:
        inputs.dtm = dtms[0].path
    elif len(dtms) > 1:
        inputs.notes.append(f"{len(dtms)} rasters in the DTM folder: none chosen automatically (keep exactly one).")
    if len(dsms) == 1:
        inputs.dsm = dsms[0].path
    elif len(dsms) > 1:
        inputs.notes.append(f"{len(dsms)} rasters in the DSM folder: none chosen automatically (keep exactly one).")
    inputs.exclusions = [
        d.path for d in datasets
        if d.folder_key in ("hydrology", "exclusions") and d.kind == "vector" and d.readable
        and (d.geometry in ("Polygon", "Line") or (d.folder_key == "exclusions" and d.geometry == "Point"))
        and d.feature_count != 0
    ]
    aois = [d for d in datasets if d.folder_key == "aoi" and d.kind == "vector" and d.readable and d.geometry == "Polygon"]
    if len(aois) == 1:
        inputs.aoi = aois[0].path
    elif len(aois) > 1:
        inputs.notes.append(f"{len(aois)} AOI layers: none chosen automatically (keep one, or pick it in the dialog).")
    inputs.centres = [
        d.path for d in datasets if d.folder_key == "centres" and d.kind == "vector" and d.readable and d.geometry == "Point"
    ]
    inputs.obstacles = [
        d.path for d in datasets
        if d.folder_key == "obstacles" and d.kind == "vector" and d.readable and d.feature_count != 0
        and d.geometry in ("Point", "Line", "Polygon", "Mixed")
    ]
    runs = folder_path(root, "runs")
    inputs.runs_folder = str(runs) if runs.is_dir() else None
    return inputs


def discover_inputs(root: str | Path, inspector: Inspector | None = None) -> DiscoveredInputs:
    """Which files the analysis should use from a data folder (no audit findings)."""
    resolved = resolve_data_root(root) or Path(root)
    datasets = scan_data_root(resolved, inspector)
    inputs = select_inputs(resolved, datasets)
    for dataset in datasets:
        if dataset.folder_key == "profiles" and dataset.kind == "profile" and _profile_kind(Path(dataset.path)) == "aircraft":
            inputs.custom_aircraft.append(dataset.path)
    return inputs


