DTM_NAME_HINT = re.compile(r"(^|[^a-z])(dtm|dem|bare|terrain|ground|bem)([^a-z]|$)", re.I)
DSM_NAME_HINT = re.compile(r"(^|[^a-z])(dsm|surface|first|canopy|chm|nDSM)([^a-z]|$)", re.I)
WATER_NAME_HINT = re.compile(r"water|lake|river|hydro|pond|reservoir|wetland|nhn|ohn|nhd|stream", re.I)


def _suggest_folder(dataset: Dataset) -> str:
    name = dataset.name
    if dataset.kind == "raster":
        if DSM_NAME_HINT.search(name):
            return "01_Elevation\\DSM"
        if DTM_NAME_HINT.search(name):
            return "01_Elevation\\DTM"
        return "01_Elevation\\DTM or 01_Elevation\\DSM"
    if dataset.kind == "vector":
        if WATER_NAME_HINT.search(name):
            return "02_Hydrology"
        if dataset.geometry == "Point":
            return "05_Search_Centres"
        if re.search(r"aoi|area|boundary|extent", name, re.I):
            return "04_AOI"
        return "02_Hydrology, 03_Exclusions or 04_AOI"
    if dataset.kind == "pointcloud":
        return "01_Elevation\\Source_PointCloud"
    return "06_Reference"


def _profile_kind(path: Path) -> str:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ""
    if not isinstance(data, dict):
        return ""
    if "tdp_diameter_m" in data:
        return "aircraft"
    if "slope_weight" in data:
        return "mission"
    if "approval_status" in data:
        return "doctrine"
    return ""


def _fmt_cell(dataset: Dataset) -> str:
    if dataset.cell_w is None:
        return "?"
    return f"{dataset.cell_w:g} m" if dataset.crs.unit in ("metre", "") else f"{dataset.cell_w:g} {dataset.crs.unit}"


def _area_km2(box: tuple[float, float, float, float] | None) -> float:
    if not box:
        return 0.0
    return max(0.0, box[2] - box[0]) * max(0.0, box[3] - box[1]) / 1.0e6


def _overlap(
    a: tuple[float, float, float, float], b: tuple[float, float, float, float], allow_point: bool = False
) -> tuple[float, float, float, float] | None:
    """The overlap of two boxes, or None. ``allow_point``: a zero-size box (a layer with ONE point) inside the other counts (v0.7.0)."""
    x_min, y_min = max(a[0], b[0]), max(a[1], b[1])
    x_max, y_max = min(a[2], b[2]), min(a[3], b[3])
    if allow_point:
        if x_max < x_min or y_max < y_min:
            return None
    elif x_max <= x_min or y_max <= y_min:
        return None
    return x_min, y_min, x_max, y_max


class _Auditor:
    def __init__(self, root: Path, datasets: list[Dataset], buffer_m: float) -> None:
        self.root = root
        self.datasets = datasets
        self.buffer_m = buffer_m
        self.findings: list[Finding] = []

    def add(self, level: str, area: str, message: str, action: str = "", dataset: Dataset | None = None) -> None:
        self.findings.append(Finding(level, area, message, action, dataset.rel if dataset else ""))

    def of(self, key: str) -> list[Dataset]:
        return [d for d in self.datasets if d.folder_key == key]

    # -- elevation ---------------------------------------------------------
    def check_raster(self, dataset: Dataset, area: str, role: str) -> None:
        if not dataset.readable:
            self.add(LEVEL_INFO, area, f"{role} '{dataset.name}' ({dataset.fmt}) was not checked here. {dataset.note}",
                     "Run '0. Set Up and Audit Data Folder' in ArcGIS Pro, or use a GeoTIFF.", dataset)
            return
        crs = dataset.crs
        size = f"{dataset.width:,} x {dataset.height:,} cells" if dataset.width else "size unknown"
        self.add(LEVEL_PASS, area, f"{role} found: '{dataset.name}' - {dataset.fmt}, {size}, cell {_fmt_cell(dataset)}, "
                                   f"{dataset.dtype or 'type ?'}, CRS {crs.label()}.", dataset=dataset)
        if dataset.bands is not None and dataset.bands != 1:
            self.add(LEVEL_FAIL, area, f"{role} has {dataset.bands} bands; an elevation raster has exactly one.",
                     "Use the single-band elevation product (not a hillshade or an RGB image).", dataset)
        if crs.kind == "unknown":
            self.add(LEVEL_WARN, area, f"{role} coordinate system is unknown (no GeoTIFF keys, .prj or .aux.xml).",
                     "Define it with 'Define Projection' (ArcGIS Pro) if you know it, or get the file again with its "
                     "georeferencing.", dataset)
        elif crs.kind == "geographic":
            self.add(LEVEL_FAIL if role == "DTM" else LEVEL_WARN, area,
                     f"{role} is in latitude/longitude ({crs.label()}). Distances and slopes need metres.",
                     "Run 'Project Raster' to the local UTM zone (e.g. NAD83(CSRS) / UTM zone 18N for Ottawa) with "
                     "the cell size in metres.", dataset)
        elif crs.web_mercator:
            self.add(LEVEL_FAIL if role == "DTM" else LEVEL_WARN, area,
                     f"{role} is in Web Mercator. It stretches distances by about 41% at Ottawa's latitude, so slopes "
                     "and landing-zone sizes would be wrong.",
                     "Run 'Project Raster' to the local UTM zone.", dataset)
        elif crs.unit and crs.unit != "metre":
            self.add(LEVEL_FAIL if role == "DTM" else LEVEL_WARN, area,
                     f"{role} horizontal unit is '{crs.unit}'. The tool needs metres.",
                     "Run 'Project Raster' to a metric system (UTM or MTM).", dataset)
        elif not crs.unit:
            self.add(LEVEL_INFO, area, f"{role} horizontal unit could not be read; metres are assumed.", dataset=dataset)
        if dataset.rotated:
            self.add(LEVEL_FAIL, area, f"{role} grid is rotated; the tool needs a north-up grid.",
                     "Use 'Project Raster' or 'Rectify' to make a north-up copy.", dataset)
        if dataset.cell_w and dataset.cell_h and abs(dataset.cell_w - dataset.cell_h) / dataset.cell_w > 0.01:
            self.add(LEVEL_FAIL, area, f"{role} cells are not square ({dataset.cell_w:g} x {dataset.cell_h:g}).",
                     "Resample to square cells (Resample tool).", dataset)
        if dataset.cell_w and crs.unit in ("metre", ""):
            if dataset.cell_w > 2.5:
                self.add(LEVEL_WARN, area, f"{role} cell size {dataset.cell_w:g} m is coarse: screening quality only.",
                         "Use 1 m data where it exists (NRCan HRDEM, provincial lidar).", dataset)
            elif dataset.cell_w > 1.0:
                self.add(LEVEL_INFO, area, f"{role} cell size {dataset.cell_w:g} m: usable; 1 m or finer is better.",
                         dataset=dataset)
        if dataset.nodata is None and dataset.fmt == "GeoTIFF":
            self.add(LEVEL_WARN, area, f"{role} has no NoData value. Void cells (often -9999, -32767 or 0 at the edges) "
                                       "would be read as real ground.",
                     "Set it with 'Set Raster Properties' (NoData) or re-export with a NoData value.", dataset)
        if dataset.dtype.startswith(("int", "uint")) and dataset.dtype not in ("int32", "uint32"):
            self.add(LEVEL_WARN, area, f"{role} is stored as whole numbers ({dataset.dtype}). Heights are rounded to "
                                       "the unit, so slope and roughness are unreliable.",
                     "Use the floating-point (32-bit) product.", dataset)
        if dataset.fmt == "GeoTIFF" and dataset.tiled is False and (dataset.width or 0) * (dataset.height or 0) > 400_000_000:
            self.add(LEVEL_INFO, area, f"{role} is a striped (not tiled) GeoTIFF; large areas read faster from a tiled one.",
                     "Optional: 'Copy Raster' to a tiled GeoTIFF, or gdal_translate -co TILED=YES.", dataset)
        if crs.vertical_unit in ("foot", "us-foot"):
            self.add(LEVEL_WARN, area, f"{role} vertical unit is {crs.vertical_unit}.",
                     "Choose 'Feet' for 'Elevation (Z) units' in the analysis.", dataset)
        stats = dataset.stats
        if stats and math.isfinite(stats.get("min", math.nan)) and math.isfinite(stats.get("max", math.nan)):
            if stats["min"] < -500.0 or stats["max"] > 9000.0:
                self.add(LEVEL_WARN, area, f"{role} values run from {stats['min']:,.1f} to {stats['max']:,.1f}: outside "
                                           "any real ground height. NoData is probably not set, or the unit is wrong.",
                         "Check the NoData value and the elevation unit.", dataset)

    def check_elevation(self) -> tuple[Dataset | None, Dataset | None]:
        dtms = [d for d in self.of("dtm") if d.kind == "raster"]
        dsms = [d for d in self.of("dsm") if d.kind == "raster"]
        dtm = dsm = None
        if not dtms:
            containers = [d for d in self.of("dtm") if d.kind == "geodatabase"]
            if containers:
                self.add(LEVEL_FAIL, "dtm", f"The DTM folder holds a geodatabase ('{containers[0].name}') whose rasters "
                                            "can only be listed inside ArcGIS Pro.",
                         "Run '0. Set Up and Audit Data Folder' in ArcGIS Pro, or export the DTM to a GeoTIFF.")
            else:
                self.add(LEVEL_FAIL, "dtm", "No DTM: the DTM folder has no elevation raster. The analysis cannot run.",
                         "Copy ONE bare-earth elevation raster (for example the HRDEM 'dtm' GeoTIFF) into "
                         "01_Elevation\\DTM.")
        elif len(dtms) > 1:
            names = ", ".join(d.name for d in dtms[:6]) + (" ..." if len(dtms) > 6 else "")
            same_grid = len({(d.crs.epsg, d.cell_w) for d in dtms}) == 1
            self.add(LEVEL_FAIL, "dtm", f"{len(dtms)} rasters in the DTM folder ({names}); the tool reads exactly one.",
                     ("They look like tiles of one survey: combine them with 'Mosaic To New Raster' (32-bit float, "
                      "1 band) or a mosaic dataset, keep that one here and move the tiles to 06_Reference."
                      if same_grid else "Keep only the DTM you want to use; move the others to 06_Reference."))
            for item in dtms:
                self.check_raster(item, "dtm", "DTM tile")
        else:
            dtm = dtms[0]
            self.check_raster(dtm, "dtm", "DTM")
            if DSM_NAME_HINT.search(dtm.name) and not DTM_NAME_HINT.search(dtm.name):
                self.add(LEVEL_WARN, "dtm", f"'{dtm.name}' is named like a surface model (DSM) but is in the DTM folder.",
                         "Check that the DTM and DSM are not swapped.", dtm)
        if not dsms:
            self.add(LEVEL_WARN, "dsm", "No DSM: trees, buildings and towers will NOT be detected and every rating is "
                                        "capped at Marginal.",
                     "Copy the surface model that matches the DTM (for example HRDEM 'dsm') into 01_Elevation\\DSM.")
        elif len(dsms) > 1:
            self.add(LEVEL_WARN, "dsm", f"{len(dsms)} rasters in the DSM folder; the tool reads exactly one, so none is "
                                        "chosen automatically.",
                     "Mosaic them into one raster, or keep only the one you want.")
        else:
            dsm = dsms[0]
            self.check_raster(dsm, "dsm", "DSM")
            if DTM_NAME_HINT.search(dsm.name) and not DSM_NAME_HINT.search(dsm.name):
                self.add(LEVEL_WARN, "dsm", f"'{dsm.name}' is named like a terrain model (DTM) but is in the DSM folder.",
                         "Check that the DTM and DSM are not swapped.", dsm)
        if dtm is not None and dsm is not None:
            self.compare_dtm_dsm(dtm, dsm)
        return dtm, dsm

    def compare_dtm_dsm(self, dtm: Dataset, dsm: Dataset) -> None:
        if os.path.normcase(os.path.abspath(dtm.path)) == os.path.normcase(os.path.abspath(dsm.path)):
            self.add(LEVEL_FAIL, "dsm", "The DSM is the same file as the DTM.", "Use the surface model in the DSM folder.", dsm)
            return
        if not (dtm.readable and dsm.readable):
            return
        if dtm.crs.kind != "unknown" and dsm.crs.kind != "unknown" and not crs_equal(dtm.crs, dsm.crs):
            self.add(LEVEL_INFO, "dsm", f"DSM coordinate system ({dsm.crs.label()}) differs from the DTM "
                                        f"({dtm.crs.label()}); it is projected onto the DTM grid during the run (slower).",
                     "Optional: 'Project Raster' the DSM with the DTM as snap raster.", dsm)
        if dtm.crs.vertical and dsm.crs.vertical and dtm.crs.vertical != dsm.crs.vertical:
            self.add(LEVEL_WARN, "dsm", f"Vertical datums differ: DTM {dtm.crs.vertical}, DSM {dsm.crs.vertical}. "
                                        "Obstacle heights (DSM minus DTM) will be offset.",
                     "Use DTM and DSM on the same vertical datum (same survey).", dsm)
        if dtm.cell_w and dsm.cell_w:
            if abs(dtm.cell_w - dsm.cell_w) > 1e-6:
                self.add(LEVEL_INFO, "dsm", f"DSM cell size {dsm.cell_w:g} differs from the DTM ({dtm.cell_w:g}); it is "
                                            "resampled onto the DTM grid during the run (slower).", dataset=dsm)
            elif dtm.extent and dsm.extent and crs_compatible(dtm.crs, dsm.crs):
                dx = ((dsm.extent[0] - dtm.extent[0]) / dtm.cell_w) % 1.0
                dy = ((dsm.extent[3] - dtm.extent[3]) / dtm.cell_w) % 1.0
                aligned = min(dx, 1.0 - dx) < 1e-3 and min(dy, 1.0 - dy) < 1e-3
                if aligned:
                    self.add(LEVEL_PASS, "dsm", "DSM is on the same grid as the DTM (same cell size and alignment): no "
                                                "resampling needed.", dataset=dsm)
                else:
                    self.add(LEVEL_INFO, "dsm", "DSM cells are offset from the DTM grid by part of a cell; it is "
                                                "resampled during the run.",
                             "Optional: re-export the DSM with the DTM as snap raster.", dsm)
        if dtm.extent and dsm.extent:
            box = extent_in(dsm, dtm.crs)
            if box is not None:
                overlap = _overlap(dtm.extent, box)
                ratio = _area_km2(overlap) / max(_area_km2(dtm.extent), 1e-12)
                if overlap is None:
                    self.add(LEVEL_FAIL, "dsm", "The DSM does not overlap the DTM at all.",
                             "Use the DSM of the same area.", dsm)
                elif ratio < 0.95:
                    self.add(LEVEL_WARN, "dsm", f"The DSM covers only {ratio:.0%} of the DTM. Obstacles are not assessed "
                                                "where the DSM is missing.",
                             "Use a DSM that covers the whole DTM, or limit the run with an AOI.", dsm)
        if dtm.stats and dsm.stats:
            dtm_mean, dsm_mean = dtm.stats.get("mean", math.nan), dsm.stats.get("mean", math.nan)
            if math.isfinite(dtm_mean) and math.isfinite(dsm_mean):
                if dsm_mean < dtm_mean - 0.5:
                    self.add(LEVEL_WARN, "dsm", f"The DSM is on average LOWER than the DTM (mean {dsm_mean:.2f} vs "
                                                f"{dtm_mean:.2f}). They may be swapped, or on different vertical datums.",
                             "Check which file is which, and their vertical datums.", dsm)
                elif abs(dsm_mean - dtm_mean) < 0.01 and abs(dsm.stats["max"] - dtm.stats["max"]) < 0.01:
                    self.add(LEVEL_WARN, "dsm", "The DSM statistics equal the DTM's: it is probably a copy of the DTM.",
                             "Use the real surface model.", dsm)
                else:
                    self.add(LEVEL_PASS, "dsm", f"DSM is higher than the DTM on average by {dsm_mean - dtm_mean:.2f} m "
                                                "(trees and buildings), as expected.", dataset=dsm)

    # -- polygons and points ----------------------------------------------
    def check_vectors(self, key: str, dtm: Dataset | None, *, want: "str | tuple[str, ...]", required_text: str,
                      missing_level: str) -> list[Dataset]:
        wanted = (want,) if isinstance(want, str) else tuple(want)
        wanted_text = " or ".join(w.lower() for w in wanted)
        items = [d for d in self.of(key) if d.kind in ("vector", "geodatabase")]
        good: list[Dataset] = []
        for dataset in items:
            label = f"'{dataset.name}'"
            if dataset.kind == "geodatabase" or not dataset.readable:
                self.add(LEVEL_INFO if dataset.kind == "geodatabase" else LEVEL_WARN, key,
                         f"{label} ({dataset.fmt}) was not checked here. {dataset.note}", dataset=dataset)
                continue
            if dataset.feature_count == 0:
                self.add(LEVEL_WARN, key, f"{label} has no features.", "Replace it with a layer that has data.", dataset)
                continue
            if dataset.geometry not in wanted:
                if "Polygon" in wanted:
                    action = "Use a polygon or line layer."
                elif dataset.geometry == "Polygon":
                    action = "Use a point layer (or 'Feature To Point' on the polygons)."
                else:
                    action = "Use a point layer."
                if want == "Polygon" and dataset.geometry == "Point":
                    action = "Points cannot exclude an area: use polygons, or 'Buffer' the points to polygons."
                self.add(LEVEL_WARN, key, f"{label} holds {dataset.geometry or 'unknown'} features; this folder needs "
                                          f"{wanted_text} features, so it is not used.", action, dataset)
                continue
            count = _features(dataset.feature_count)
            if dataset.crs.kind == "unknown":
                self.add(LEVEL_WARN, key, f"{label}: coordinate system unknown (no .prj).",
                         "Copy the .prj file with the shapefile, or 'Define Projection'.", dataset)
            if dtm is not None and dtm.extent and dataset.extent:
                box = extent_in(dataset, dtm.crs)
                if box is not None and _overlap(dtm.extent, box, allow_point=True) is None:
                    self.add(LEVEL_WARN, key, f"{label} does not overlap the DTM, so it has no effect.",
                             "Use the layer for the DTM's area.", dataset)
                    continue
                if box is None:
                    self.add(LEVEL_INFO, key, f"{label} ({dataset.crs.label()}) could not be compared with the DTM "
                                              "here; ArcGIS projects it during the run.", dataset=dataset)
            self.add(LEVEL_PASS, key, f"{label}: {dataset.fmt}, {count}, {dataset.geometry.lower()}s, CRS "
                                      f"{dataset.crs.label()}.", dataset=dataset)
            if dataset.geometry == "Line":
                self.add(LEVEL_INFO, key, f"{label} holds LINES: each is widened to the analysis 'line width' (default "
                                          "10 m in total). Rivers wider than that, and lake outlines, are not covered "
                                          "by it.",
                         "Use water polygons for wide rivers and lakes, or raise the line width in the analysis.",
                         dataset)
            if dataset.geometry == "Point" and key == "exclusions":
                self.add(LEVEL_INFO, key, f"{label} holds POINTS: each excludes a small circle around it (default radius "
                                          "10 m, set by 'Radius given to exclusion POINTS' in the analysis).",
                         "Raise the radius for large hazards, or give them as polygons.", dataset)
            good.append(dataset)
        if not good and missing_level:
            self.add(missing_level, key, required_text[0], required_text[1])
        return good

    def check_obstacle_heights(self, items: list[Dataset]) -> None:
        for dataset in items:
            assumed = int((dataset.stats or {}).get("assumed_heights", 0))
            if dataset.note and dataset.fmt in ("FAA DOF (.dat)", "CSV obstacle list"):
                self.add(LEVEL_INFO if not assumed else LEVEL_WARN, "obstacles", f"'{dataset.name}': {dataset.note}.",
                         "Obstacles without a height use the default (30 m) and are marked ASSUMED in the report. "
                         "Add a height column for better results." if assumed else "", dataset)
        if items:
            self.add(LEVEL_INFO, "obstacles", "Obstacle heights are above ground. Approaches are checked against every "
                                              "listed obstacle; check the heights of the ones that matter.")

    def check_aoi(self, aois: list[Dataset], dtm: Dataset | None) -> None:
        if len(aois) > 1:
            self.add(LEVEL_WARN, "aoi", f"{len(aois)} AOI layers: none is filled in automatically.",
                     "Keep one in 04_AOI (move others to 06_Reference), or choose it in the dialog.")
            return
        if len(aois) != 1 or dtm is None or not dtm.extent:
            return
        aoi = aois[0]
        box = extent_in(aoi, dtm.crs)
        if box is None:
            return
        overlap = _overlap(dtm.extent, box)
        if overlap is None:
            self.add(LEVEL_FAIL, "aoi", f"The AOI '{aoi.name}' does not overlap the DTM.",
                     "Use an AOI inside the DTM, or the DTM of the AOI's area.", aoi)
            return
        gaps = {"west": box[0] - dtm.extent[0], "east": dtm.extent[2] - box[2],
                "south": box[1] - dtm.extent[1], "north": dtm.extent[3] - box[3]}
        short = [side for side, gap in gaps.items() if gap < self.buffer_m - 1.0]
        if short:
            self.add(LEVEL_WARN, "aoi", f"The DTM ends less than {self.buffer_m:,.0f} m (approach range plus touchdown "
                                        f"point and ring) beyond the AOI on the {', '.join(short)} side(s). Approaches "
                                        "toward there cannot be fully checked; sites near that edge may be Unassessed.",
                     "Extend the DTM/DSM on those sides, or shrink the AOI.", aoi)
        else:
            self.add(LEVEL_PASS, "aoi", f"The DTM extends at least {self.buffer_m:,.0f} m beyond the AOI on every side.",
                     dataset=aoi)
        self.add(LEVEL_INFO, "aoi", f"AOI bounding box: {_area_km2(overlap):,.1f} km2 inside the DTM.", dataset=aoi)

    def check_centres(self, centres: list[Dataset], dtm: Dataset | None) -> None:
        for item in centres:
            if dtm is None or not dtm.extent or not item.extent:
                continue
            box = extent_in(item, dtm.crs)
            if box is not None and _overlap(dtm.extent, (box[0] - 0.5, box[1] - 0.5, box[2] + 0.5, box[3] + 0.5)) is None:
                self.add(LEVEL_WARN, "centres", f"The points in '{item.name}' lie outside the DTM.",
                         "Use points inside the DTM (with data around them for the approaches).", item)
        if centres:
            self.add(LEVEL_INFO, "centres", f"{len(centres)} search-centre layer(s) available. They are NOT filled in "
                                            "automatically: choose one in 'Search around a point' when you want a "
                                            "radius search.")

    # -- other folders -------------------------------------------------------
    def check_profiles(self) -> None:
        from .config import ProfileError, load_aircraft_profile, load_doctrine_profile, load_mission_profile

        loaders = {"aircraft": load_aircraft_profile, "mission": load_mission_profile, "doctrine": load_doctrine_profile}
        for dataset in self.of("profiles"):
            if dataset.kind != "profile":
                continue
            kind = _profile_kind(Path(dataset.path))
            if not kind:
                self.add(LEVEL_WARN, "profiles", f"'{dataset.name}' is not a recognised aircraft, mission or doctrine profile.",
                         "Start from a copy of a shipped profile.", dataset)
                continue
            try:
                profile = loaders[kind](dataset.path)
            except ProfileError as error:
                self.add(LEVEL_WARN, "profiles", f"{kind.title()} profile '{dataset.name}' is invalid: {error}",
                         "Fix the value named, then audit again.", dataset)
                continue
            dataset.profile_type = kind
            self.add(LEVEL_PASS, "profiles", f"{kind.title()} profile '{dataset.name}' is valid "
                                             f"({getattr(profile, 'display_name', '')}).",
                     "Aircraft: choose 'Custom profile file...' and this file." if kind == "aircraft" else "", dataset)

    def check_misc(self) -> None:
        for dataset in self.datasets:
            if dataset.kind == "archive":
                self.add(LEVEL_WARN, dataset.folder_key or "general", f"'{dataset.name}' is a compressed archive; the tool "
                                                                      "cannot read inside it.",
                         "Extract it here (right-click > Extract All), then delete or move the archive.", dataset)
            elif dataset.kind == "pointcloud" and dataset.folder_key != "pointcloud":
                self.add(LEVEL_WARN, dataset.folder_key or "general", f"'{dataset.name}' is a point cloud; it belongs in "
                                                                      "01_Elevation\\Source_PointCloud.",
                         "Move it, and make DTM/DSM rasters from it with 'LAS Dataset To Raster'.", dataset)
            elif dataset.folder_key is None and dataset.kind in ("raster", "vector", "geodatabase"):
                self.add(LEVEL_WARN, "general", f"'{dataset.rel}' is outside the standard folders and is not used.",
                         f"Move it to {_suggest_folder(dataset)}.", dataset)
            elif dataset.folder_key in ("dtm", "dsm") and dataset.kind in ("vector", "geodatabase"):
                self.add(LEVEL_WARN, dataset.folder_key, f"'{dataset.name}' is a {dataset.kind} in an elevation folder.",
                         f"Move it to {_suggest_folder(dataset)}.", dataset)
            elif dataset.folder_key in ("hydrology", "exclusions", "aoi", "centres", "obstacles") and dataset.kind == "raster":
                self.add(LEVEL_WARN, dataset.folder_key, f"'{dataset.name}' is a raster; this folder needs vector layers.",
                         f"Move it to {_suggest_folder(dataset)}, or convert it ('Raster To Polygon').", dataset)
            elif dataset.kind == "other" and dataset.folder_key not in ("profiles",):
                self.add(LEVEL_INFO, dataset.folder_key or "general", f"'{dataset.rel}' is not a recognised GIS file and "
                                                                      "is ignored.", dataset=dataset)
        clouds = [d for d in self.of("pointcloud") if d.kind == "pointcloud"]
        if clouds:
            self.add(LEVEL_INFO, "pointcloud", f"{len(clouds)} point-cloud file(s) kept as source data (not read by the "
                                               "analysis).")
        reference = folder_path(self.root, "reference")
        if reference.is_dir():
            count = sum(1 for entry in reference.iterdir() if entry.name.lower() != "readme.txt")
            if count:
                self.add(LEVEL_INFO, "reference", f"{count} item(s) in 06_Reference (not read by the analysis).")
        runs = folder_path(self.root, "runs")
        if runs.is_dir():
            finished = unfinished = 0
            for child in runs.iterdir():
                if child.is_dir():
                    if (child / "HLZ_Report.html").is_file():
                        finished += 1
                    elif (child / "hlz_run.log").is_file():
                        unfinished += 1
            if finished or unfinished:
                text = f"08_Runs holds {finished} finished run(s)"
                if unfinished:
                    text += f" and {unfinished} unfinished run(s) (re-run with the same run name to resume)"
                self.add(LEVEL_INFO, "runs", text + ".")

    def check_general(self, dtm: Dataset | None, created: list[str]) -> None:
        missing = [spec.path.replace("/", os.sep) for spec in FOLDERS if not folder_path(self.root, spec.key).is_dir()]
        if missing:
            self.add(LEVEL_WARN, "general", f"Standard folder(s) missing: {', '.join(missing)}.",
                     "Run the set-up again (it only adds missing folders).")
        if created:
            self.add(LEVEL_INFO, "general", f"Created: {', '.join(created)}.")
        if not is_data_root(self.root):
            self.add(LEVEL_INFO, "general", f"No {MARKER_NAME} marker yet; the set-up writes it.")
        message = path_warning(str(self.root))
        if message:
            self.add(LEVEL_WARN, "general", message.replace("C:\\GIS\\HLZ_runs", "C:\\GIS\\HLZ_DATA"),
                     "Move the data folder to a short local path.")
        try:
            free_gb = shutil.disk_usage(self.root).free / 1024 ** 3
        except OSError:
            free_gb = None
        if free_gb is not None:
            area = _area_km2(dtm.extent) if dtm is not None and dtm.crs.metric_projected else 0.0
            need_gb = max(5.0, 3.0 * area / 1000.0 + 2.0)
            if free_gb < need_gb:
                self.add(LEVEL_WARN, "general", f"Only {free_gb:,.1f} GB free on this disk; a full run of this DTM may "
                                                f"need about {need_gb:,.0f} GB.",
                         "Free space, or put 08_Runs results on a larger local disk.")
            else:
                self.add(LEVEL_PASS, "general", f"{free_gb:,.0f} GB free on the disk (estimate for a full run of this "
                                                f"DTM: up to {need_gb:,.0f} GB).")
        if dtm is not None and dtm.extent and dtm.crs.metric_projected:
            cells = (dtm.width or 0) * (dtm.height or 0)
            self.add(LEVEL_INFO, "dtm", f"DTM covers {_area_km2(dtm.extent):,.1f} km2 ({cells:,} cells).", dataset=dtm)


def audit_data_root(
    root: str | Path,
    *,
    create: bool = False,
    aircraft_profile: str | Path | None = None,
    inspector: Inspector | None = None,
    write_reports: bool = True,
) -> AuditResult:
    """Check a data folder (optionally creating missing folders first) and write the reports to 09_Audit."""
    root_path = Path(root)
    resolved = resolve_data_root(root_path)
    if resolved is not None and resolved != root_path and not create:
        root_path = resolved
    created = create_data_root(root_path) if create else []
    if not root_path.is_dir():
        raise FileNotFoundError(f"The data folder does not exist: {root_path}. Create it first (init).")
    buffer_m, aircraft_name = DEFAULT_BUFFER_M, "Generic medium (default)"
    if aircraft_profile:
        from .config import load_aircraft_profile

        aircraft = load_aircraft_profile(aircraft_profile)
        buffer_m = float(aircraft.approach_range_m + aircraft.analysis_radius_m)
        aircraft_name = aircraft.display_name
    datasets = scan_data_root(root_path, inspector)
    auditor = _Auditor(root_path, datasets, buffer_m)
    dtm, _dsm = auditor.check_elevation()
    auditor.check_vectors(
        "hydrology", dtm, want=("Polygon", "Line"), missing_level=LEVEL_WARN,
        required_text=("No water data: lakes, ponds and rivers are NOT excluded and can be rated as excellent "
                       "landing zones.",
                       "Copy a water layer (polygons for lakes and wide rivers, lines for streams: Ontario Hydro "
                       "Network, NRCan NHN, USGS NHD, OpenStreetMap water) into 02_Hydrology."),
    )
    auditor.check_vectors(
        "exclusions", dtm, want=("Polygon", "Line", "Point"), missing_level=LEVEL_INFO,
        required_text=("No other exclusion areas (optional: wetlands, built-up or restricted areas).", ""),
    )
    obstacle_layers = auditor.check_vectors(
        "obstacles", dtm, want=("Point", "Line", "Polygon", "Mixed"), missing_level=LEVEL_INFO,
        required_text=("No obstacle list: towers, masts and wires that the lidar surface model misses are NOT "
                       "considered, so a glide path can be rated clear when a tower stands in it.",
                       "Recommended: put an FAA DOF file, an OpenStreetMap GeoJSON, a CSV (latitude, longitude, "
                       "height) or an obstacle layer in 10_Obstacles."),
    )
    auditor.check_obstacle_heights(obstacle_layers)
    aois = auditor.check_vectors(
        "aoi", dtm, want="Polygon", missing_level=LEVEL_INFO,
        required_text=("No AOI: the analysis uses the current map view, or the whole DTM.",
                       "Optional: put one area-of-interest polygon in 04_AOI."),
    )
    auditor.check_aoi(aois, dtm)
    centres = auditor.check_vectors("centres", dtm, want="Point", missing_level="", required_text=("", ""))
    auditor.check_centres(centres, dtm)
    auditor.check_profiles()
    auditor.check_misc()
    auditor.check_general(dtm, created)
    inputs = select_inputs(root_path, datasets)
    inputs.custom_aircraft = [d.path for d in datasets if d.profile_type == "aircraft"]
    levels = {item.level for item in auditor.findings}
    status = STATUS_NOT_READY if LEVEL_FAIL in levels or inputs.dtm is None else (
        STATUS_WARNINGS if LEVEL_WARN in levels else STATUS_READY)
    findings = sorted(auditor.findings, key=lambda item: (LEVEL_ORDER[item.level], _area_rank(item.area)))
    result = AuditResult(
        root=str(root_path), status=status, checked_at=_dt.datetime.now().isoformat(timespec="seconds"),
        tool_version=__version__, layout_version=LAYOUT_VERSION, buffer_m=buffer_m, aircraft=aircraft_name,
        created_folders=created, findings=findings, datasets=datasets, inputs=inputs,
    )
    if write_reports:
        result.reports = write_audit_reports(result)
    return result


def _area_rank(area: str) -> int:
    order = [spec.key for spec in FOLDERS]
    return order.index(area) if area in order else (-1 if area == "general" else len(order))


def _area_title(area: str) -> str:
    if area == "general":
        return "General"
    spec = FOLDER_BY_KEY.get(area)
    return spec.path.replace("/", "\\") if spec else area


